#!/usr/bin/env python3
"""PreToolUse hook: each MakeItLean agent role may write only its own files.

The role is the subagent's name, which Claude Code passes to hooks as `agent_type`
(`.claude/agents/mil-*.md`). Calls from any other agent, or from the main session, are not
restricted here (the frozen-file guard, `guard_locked.py`, still applies to everyone).

Paths are judged relative to their app: the nearest enclosing directory with a `mil.json`
(`examples/<app>/`, `bench/verina/runs/…/<app>/`; never `templates/`):

  spec area   REQUIREMENTS.md, mil.json, <App>/Spec.lean, <App>/Spec/**     (spec author)
  critic      <App>/SpecCritic/**                                            (spec critic)
  proofs      impl/**/Proofs.lean, impl/**/Proofs/**, impl/fill.json         (prover)
  impl        the rest of examples/<app>/ (impl/, a non-Lean shell, tests)   (implementer)
  trust       TRUST.md                                                       (auditor)
  everyone    FRICTION.md (the friction log is shared)

Nothing outside `examples/<app>/` inside the repository is writable by a role (the framework,
LeanKV and the templates are not the app's to change); paths outside the repository (scratch
space) are allowed. Exit 2 blocks the call and the reason on stderr is shown to the agent.
"""
import json, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import shellwrites  # noqa: E402

ROLES = {
    "mil-spec-author": {"spec"},
    "mil-spec-critic": {"critic"},
    "mil-implementer": {"impl"},
    "mil-prover": {"proofs"},
    "mil-auditor": {"trust"},
}
WRITE_TOOLS = {"Edit", "Write", "MultiEdit", "NotebookEdit"}
BASH_WRITES = re.compile(r"(>|\btee\b|\bsed\s+-i|\bperl\s+-i|\bmv\b|\bcp\b|\brm\b|\btruncate\b|\bdd\b|\bpatch\b)")


def repo_root(start):
    d = os.path.abspath(start)
    while True:
        if os.path.isdir(os.path.join(d, "judge")) and os.path.isfile(os.path.join(d, "lakefile.lean")):
            return d
        parent = os.path.dirname(d)
        if parent == d:
            return None
        d = parent


def app_root(full, root):
    """The app holding `full`: its nearest enclosing directory with a `mil.json`, inside the
    repository but not under `templates/` (examples/<app>/, bench/verina/runs/…/<app>/, …).
    None when the path belongs to no app (the framework, LeanKV, templates, docs)."""
    d = full if os.path.isdir(full) else os.path.dirname(full)
    while d.startswith(root + "/"):
        if os.path.isfile(os.path.join(d, "mil.json")):
            rel = os.path.relpath(d, root)
            return None if rel.split(os.sep)[0] == "templates" else d
        d = os.path.dirname(d)
    return None


def area(full, root):
    """The area of an absolute path inside the repository `root`, or None outside every app."""
    app = app_root(full, root)
    if app is None:
        return None
    sub = os.path.relpath(full, app).split(os.sep)
    name = sub[-1]
    if sub == ["FRICTION.md"]:
        return "everyone"
    if name.startswith("REQUIREMENTS") and name.endswith(".md") and "SpecCritic" not in sub:
        return "spec"  # any requirements document of the app (e.g. http/REQUIREMENTS.md)
    if sub == ["TRUST.md"]:
        return "trust"
    if sub in (["REQUIREMENTS.md"], ["mil.json"]):
        return "spec"
    if sub[0] == "impl":
        if sub == ["impl", "fill.json"] or name == "Proofs.lean" or "Proofs" in sub[:-1]:
            return "proofs"
        return "impl"
    if len(sub) >= 2 and sub[1] == "SpecCritic":
        return "critic"
    if (len(sub) == 2 and name == "Spec.lean") or (len(sub) >= 2 and sub[1] == "Spec"):
        return "spec"
    if sub == ["spec.lock"] or sub == ["SPEC_REVIEW.md"]:
        return "tool"  # written by `mil freeze` / `mil review`, never by hand
    return "impl"  # anything else in the app (a non-Lean shell, docs, tests)


def deny(role, rel, why):
    sys.stderr.write(f"BLOCKED for role {role}: {rel} {why}. Your role may write only "
                     f"{sorted(ROLES[role] | {'everyone'})} files (see agents/AGENTS.md, Roles). "
                     "If another role's file must change, stop and report it.\n")
    sys.exit(2)


def root_of(path):
    """The repository or worktree holding `path` (found from the target, not the cwd)."""
    d = path if os.path.isdir(path) else os.path.dirname(path)
    while d and not os.path.isdir(d):
        d = os.path.dirname(d)
    r = repo_root(d) if d else None
    return os.path.realpath(r) if r else None


def check_path(role, cwd, p):
    full = os.path.realpath(p if os.path.isabs(p) else os.path.join(cwd, p))
    root = root_of(full)
    if root is None:
        return  # outside any MakeItLean repository (scratch space)
    rel = os.path.relpath(full, root)
    a = area(full, os.path.realpath(root))
    if a is None:
        deny(role, rel, "is framework or substrate code, outside every app")
    if a == "tool":
        deny(role, rel, "is generated by mil (`mil freeze`, `mil review`), not edited by hand")
    if a != "everyone" and a not in ROLES[role]:
        deny(role, rel, f"belongs to the {a} area")


def main():
    try:
        data = json.load(sys.stdin)
    except Exception:
        sys.exit(0)
    role = data.get("agent_type") or ""
    if role not in ROLES:
        sys.exit(0)
    cwd = data.get("cwd") or os.getcwd()
    tool = data.get("tool_name", "")
    inp = data.get("tool_input", {}) or {}
    if tool in WRITE_TOOLS:
        p = inp.get("file_path") or inp.get("notebook_path")
        if not p:
            sys.stderr.write(f"BLOCKED for role {role}: {tool} call without a file path.\n")
            sys.exit(2)
        check_path(role, cwd, p)
    elif tool == "Bash":
        cmd = inp.get("command", "")
        targets = shellwrites.write_targets(cmd, cwd)
        if targets is None:  # unparseable: check every existing path-like word, as before
            targets = [t for t in re.findall(r"[\w./-]+", cmd) if "/" in t] if BASH_WRITES.search(cmd) else []
        for t in targets + shellwrites.inline_script_paths(cmd, cwd):
            check_path(role, cwd, t)
    sys.exit(0)


if __name__ == "__main__":
    main()

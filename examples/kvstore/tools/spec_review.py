#!/usr/bin/env python3
"""Generate SPEC_REVIEW.md: each spec declaration's English text beside its Lean statement.

Usage: python3 tools/spec_review.py  (run from examples/kvstore). Candidate for `mil spec-review`.
"""
import re, pathlib, hashlib

ORDER = ["Bytes", "Model", "Properties", "Wire", "Log", "Contract", "Store", "Examples"]
TITLES = {
    "Bytes": "Byte strings, limits and key order (R1, R2, R8a)",
    "Model": "The reference state machine (R3–R9)",
    "Properties": "Requirement-level properties of the reference model (R1–R8)",
    "Wire": "Text encoding, grammar and exit codes (R14, R15, R22)",
    "Log": "Log format and recovery (R8, R11, R12)",
    "Contract": "Implementation contract: the index (R9, R17)",
    "Store": "The durable store against a model file system (R10–R12, R21)",
    "Examples": "Worked examples from the requirements",
}
DECL = re.compile(r"(/-- English:(?P<doc>(?:(?!-/).)*)-/)\s*\n(?P<pre>(?:set_option[^\n]*\n)?)"
                  r"(?P<kind>theorem|def|abbrev|inductive|structure|class|instance)\s+(?P<name>[^\s(:{\[]+)?",
                  re.S)

def body_start(src, start):
    """Where the body begins: the first `:=` at bracket depth 0 that is not a `let` binding,
    or `where`, or a first constructor line. Returns (offset, token) relative to `start`."""
    rest = src[start:]
    depth = 0
    i = 0
    while i < len(rest):
        c = rest[i]
        if c in "([{⟨": depth += 1
        elif c in ")]}⟩": depth -= 1
        elif depth == 0:
            if rest.startswith(":=", i):
                line_start = rest.rfind("\n", 0, i) + 1
                if not re.search(r"\blet\s+[\w'.]+\s*(:[^=]*)?$", rest[line_start:i]):
                    return i, ":="
            elif rest.startswith("where", i) and (i == 0 or not rest[i-1].isalnum()):
                return i, "where"
            elif rest.startswith("\n  |", i):
                return i, "|"
        i += 1
    return None

def header(src, start):
    """Declaration text up to its body."""
    rest = src[start:]
    m = body_start(src, start)
    return rest[: m[0]].rstrip() if m else rest.split("\n")[0]

def body_is_sorry(src, start):
    m = body_start(src, start)
    if not m or m[1] != ":=": return False
    return src[start + m[0] + 2:].lstrip().startswith("sorry")

def main():
    root = pathlib.Path("LeanKV/Spec")
    out = ["# LeanKV — Spec review (Stage 2)", "",
           "> Generated by `tools/spec_review.py` from the Lean sources. Do not edit by hand.",
           "> Each entry shows the plain-English meaning (left of the rule) and the exact Lean statement.",
           "> **Status** says whether a theorem is already proven or is an obligation for the implementation.",
           "> Proof-step lemmas (already proven) are listed compactly at the end of each section.", ""]
    digest = hashlib.sha256()
    counts = {"proven": 0, "obligation": 0, "hole": 0}
    for name in ORDER:
        path = root / f"{name}.lean"
        src = path.read_text()
        digest.update(src.encode())
        out += [f"## {TITLES[name]}", f"`{path}`", ""]
        main_items, lemmas = [], []
        for m in DECL.finditer(src):
            doc = " ".join(m.group("doc").split())
            kind, dname = m.group("kind"), m.group("name") or "(anonymous)"
            sig = header(src, m.start("kind"))
            hole = "IMPLEMENTATION HOLE" in doc
            if kind == "theorem":
                if body_is_sorry(src, m.start("kind")):
                    status = "**Obligation** — about an implementation hole; proven in Stage 4"
                    counts["obligation"] += 1
                else:
                    status = "Proven"
                    counts["proven"] += 1
            elif hole:
                status = "**Implementation hole** — filled by the implementer; nothing else may change"
                counts["hole"] += 1
            else:
                status = None
            is_lemma = (kind == "theorem" and status == "Proven" and not re.search(r"\(R\d", doc)
                        and name in ("Properties", "Wire", "Log"))
            if is_lemma:
                lemmas.append(f"- `{dname}` — {doc}")
                continue
            entry = [f"### `{dname}` ({kind})", "", doc, ""]
            if status: entry += [f"*Status:* {status}", ""]
            entry += ["```lean", sig, "```", ""]
            main_items += entry
        out += main_items
        if lemmas:
            out += ["<details><summary>Proof-step lemmas (proven)</summary>", ""] + lemmas + ["", "</details>", ""]
    out[2:2] = [f"> Spec sources SHA-256: `{digest.hexdigest()}`",
                f"> Theorems proven: {counts['proven']}. Obligations for the implementation: "
                f"{counts['obligation']}. Implementation holes: {counts['hole']}."]
    pathlib.Path("SPEC_REVIEW.md").write_text("\n".join(out) + "\n")
    print(f"wrote SPEC_REVIEW.md ({counts})")

if __name__ == "__main__":
    main()

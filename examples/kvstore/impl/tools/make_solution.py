#!/usr/bin/env python3
"""Generate the comparator solution from the frozen spec (Stage 4/6).

- LeanKVSol/Base/*.lean: verbatim copies of the frozen spec files, minus the implementation holes,
  the definitions built on them, and the obligation theorems. Core and Proofs import these.
- LeanKVSol/Holes.lean: the removed declarations, verbatim, except that each hole's `sorry` body
  is replaced by the core function and each obligation's `sorry` proof by its proof below.

The comparator then checks every statement and transitive definition against the frozen spec,
so copying adds nothing to the trusted base. Run from examples/kvstore/impl.
"""
import pathlib, re

SPEC = pathlib.Path("../LeanKV/Spec")
FILES = ["Bytes", "Model", "Properties", "Wire", "Log", "Contract", "Store"]
REMOVE = {
    "Impl.step", "impl_run_eq", "impl_toList_eq", "impl_height_le",
    "Impl.encodeRecord", "Impl.recover", "impl_encodeRecord_eq", "impl_recover_eq",
    "Impl.openStore", "Impl.exec",
    "store_no_faults", "store_crash_consistent", "store_refuses_corrupt", "storeCheck_spec",
}
# Hole bodies and obligation proofs. A missing entry keeps `sorry` (work in progress).
BODIES = {
    "Impl.step": "LeanKV.Core.step",
    "Impl.encodeRecord": "LeanKV.Core.encodeRecord",
    "Impl.recover": "LeanKV.Core.recover",
    "Impl.openStore": "LeanKV.Core.openStore",
    "Impl.exec": "LeanKV.Core.exec h c",
    "impl_run_eq": "by rw [LeanKV.Proofs.runTree_eq]; exact (LeanKV.Proofs.core_run_eq cmds).1",
    "impl_toList_eq": "by rw [LeanKV.Proofs.runTree_eq]; exact (LeanKV.Proofs.core_run_eq cmds).2",
    "impl_height_le": "by rw [LeanKV.Proofs.runTree_eq]; exact LeanKV.Proofs.core_height_le cmds",
    "impl_encodeRecord_eq": "LeanKV.Proofs.core_encodeRecord_eq ops",
    "impl_recover_eq": "LeanKV.Proofs.core_recover_eq b",
    "storeCheck_spec": "LeanKV.Proofs.coreCheck_spec st",
    "store_refuses_corrupt": "LeanKV.Proofs.core_refuses_corrupt hc cmds φ",
    "store_no_faults": "LeanKV.Proofs.core_no_faults hs0 cmds",
    "store_crash_consistent": "LeanKV.Proofs.core_crash_consistent hs0 cmds φ ch",
}
# Extra solution-only lemmas, emitted right after the named declaration.
HELPERS: dict = {}
CHUNK = re.compile(r"(?m)^(?=/--|/-!|set_option |end LeanKV|#)")
NAME = re.compile(r"(?:theorem|def|abbrev|instance|structure|inductive|class)\s+([\w.]+)")

def chunks(src):
    parts = CHUNK.split(src)
    return parts

def name_of(chunk):
    if not chunk.startswith("/--"):
        return None
    m = NAME.search(chunk)
    return m.group(1) if m else None

def main():
    out = pathlib.Path("LeanKVSol/Base"); out.mkdir(parents=True, exist_ok=True)
    removed = []
    for f in FILES:
        src = (SPEC / f"{f}.lean").read_text()
        src = re.sub(r"(?m)^import LeanKV\.Spec\.(\w+)", r"import LeanKVSol.Base.\1", src)
        kept = []
        for c in chunks(src):
            n = name_of(c)
            if n in REMOVE:
                removed.append((f, n, c))
            else:
                kept.append(c)
        header = f"-- GENERATED by tools/make_solution.py from the frozen ../LeanKV/Spec/{f}.lean. Do not edit.\n"
        (out / f"{f}.lean").write_text(header + "".join(kept))
    assert {n for _, n, _ in removed} == REMOVE, REMOVE - {n for _, n, _ in removed}
    body = []
    for f, n, c in removed:
        if n in BODIES:
            # replace the final `sorry` (the hole body / the proof) only
            i = c.rfind("sorry")
            c = c[:i] + BODIES[n] + c[i + len("sorry"):]
        body.append(c.rstrip() + "\n\n")
        if n in HELPERS:
            body.append(HELPERS[n] + "\n\n")
    holes = ("-- GENERATED by tools/make_solution.py. The comparator's solution module.\n"
             "import LeanKVImpl.Core\nimport LeanKVImpl.Proofs\n\nnamespace LeanKV.Spec\n\n" + "".join(body) + "end LeanKV.Spec\n")
    pathlib.Path("LeanKVSol/Holes.lean").write_text(holes)
    print("removed:", len(removed), "| still `sorry`:",
          sorted(n for _, n, c in removed if n not in BODIES and "sorry" in c.split(":=")[-1]))

if __name__ == "__main__":
    main()
